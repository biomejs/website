use crate::legacy_rule_routes::LEGACY_RULE_ROUTES;
use crate::lintdoc::to_website_language;
use crate::project_root;
use anyhow::Result;
use biome_analyze::{GroupCategory, Queryable, RegistryVisitor, Rule, RuleCategory, RuleGroup};
use biome_css_syntax::CssLanguage;
use biome_graphql_syntax::GraphqlLanguage;
use biome_html_syntax::HtmlLanguage;
use biome_js_syntax::JsLanguage;
use biome_json_syntax::JsonLanguage;
use biome_markdown_syntax::MarkdownLanguage;
use biome_rowan::Language;
use biome_string_case::Case;
use std::collections::BTreeMap;
use std::fmt::Write;
use std::fs;

#[derive(Default)]
struct Redirects {
    data: BTreeMap<String, String>,
}

impl Redirects {
    fn push_redirect<R, L>(&mut self)
    where
        L: Language,
        R: Rule<Options: Default, Query: Queryable<Language = L, Output: Clone>> + 'static,
    {
        let rule_name = R::METADATA.name;
        let rule_slug = Case::Kebab.convert(rule_name);
        let path_prefix = if <R::Group as RuleGroup>::Category::CATEGORY == RuleCategory::Action {
            "assist/actions"
        } else {
            "linter/rules"
        };
        let root_path = format!("/{path_prefix}/{rule_slug}");
        let language_path = format!("{root_path}/{}", to_website_language(R::METADATA.language));

        self.data.insert(root_path, language_path.clone());
        self.data
            .insert(format!("/{path_prefix}/{rule_name}"), language_path);
    }
}

impl RegistryVisitor<JsLanguage> for Redirects {
    fn record_rule<R>(&mut self)
    where
        R: Rule<Query: Queryable<Language = JsLanguage, Output: Clone>> + 'static,
    {
        self.push_redirect::<R, JsLanguage>();
    }
}

