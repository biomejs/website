pub fn generate_redirects() -> Result<()> {
    let mut redirects = Redirects::default();

    biome_js_analyze::visit_registry(&mut redirects);
    biome_json_analyze::visit_registry(&mut redirects);
    biome_css_analyze::visit_registry(&mut redirects);
    biome_graphql_analyze::visit_registry(&mut redirects);
    biome_html_analyze::visit_registry(&mut redirects);
    biome_markdown_analyze::visit_registry(&mut redirects);

    // Keep the target language of pre-migration URLs stable.
    for &(path_prefix, rule_name, rule_slug, language) in LEGACY_RULE_ROUTES {
        let root_path = format!("/{path_prefix}/{rule_slug}");
        let language_path = format!("{root_path}/{language}");
        redirects.data.insert(root_path, language_path.clone());
        redirects
            .data
            .insert(format!("/{path_prefix}/{rule_name}"), language_path);
    }

    let mut content = String::new();
    content.push_str("// This file is generated by the codegen. Do not edit it manually.\n");
    content.push_str("export default {\n");

    for (from, to) in redirects.data {
        writeln!(content, "  '{from}': '{to}',")?;
    }

    content.push_str("};\n");
    fs::write(project_root().join("redirects.js"), content)?;

    Ok(())
}
